// Builds docs/design/compiler/data.js: real data from the compiler for the mockups of the Compile mode (task T55).
// The mockups are static pages, so they cannot compile anything; this file is what the compiler produced for the sieve
// example (bench/sieve.oak), with the numbers measured by `npm run bench` on the machine named in the README.
//
//   npx tsx scripts/mockup-compiler-data.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { compile, runCompiled } from "../src/core/compile/index";
import { tokenize } from "../src/core/lexer/lexer";
import { run } from "../src/core/run";

const root = join(import.meta.dirname, "..");
const source = readFileSync(join(root, "bench", "sieve.oak"), "utf8");

// ---- highlighted source: per line, a list of [class, text] (the same classes as docs/design/mockups)
const TYPES = new Set(["int", "float", "string", "boolean", "char", "void", "var"]);
const LITERALS = new Set(["true", "false", "null"]);
const tokens = tokenize(source, { includeComments: true }).tokens.filter((t) => t.type !== "eof");
const classOf = (index: number): string => {
  const t = tokens[index]!;
  if (t.type === "comment") return "cm";
  if (t.type === "keyword") return TYPES.has(t.text) ? "ty" : LITERALS.has(t.text) ? "lit" : "kw";
  if (t.type === "int" || t.type === "float") return "num";
  if (t.type === "string" || t.type === "char") return "str";
  if (t.type === "identifier") return tokens[index + 1]?.text === "(" ? "fn" : "id";
  return "p";
};
const pieces: [string, string][] = [];
let cursor = 0;
tokens.forEach((t, i) => {
  if (t.span.start.offset > cursor) pieces.push(["ws", source.slice(cursor, t.span.start.offset)]);
  pieces.push([classOf(i), t.text]);
  cursor = t.span.end.offset;
});
if (cursor < source.length) pieces.push(["ws", source.slice(cursor)]);
const lines: [string, string][][] = [[]];
for (const [cls, text] of pieces) {
  text.split("\n").forEach((part, k) => {
    if (k > 0) lines.push([]);
    if (part !== "") lines[lines.length - 1]!.push([cls, part.replace(/\r/g, "")]);
  });
}
while (lines.length > 0 && lines[lines.length - 1]!.length === 0) lines.pop();

// ---- the module
const compiled = compile(source);
if (!compiled.ok || compiled.wat === null || compiled.wasm === null) throw new Error("the sieve did not compile");
const ran = runCompiled(compiled);
const interpreted = run(source, { trace: false, limits: { maxSteps: 2_000_000_000, maxTimeMs: 300_000 } });
if (ran.stdout !== interpreted.stdout) throw new Error("the two modes differ");

// The WAT as functions: its text, split at each top-level (func ...). What is not a function stays in "head".
const watLines = compiled.wat.split("\n");
const functions: { name: string; origin: string; lines: string[] }[] = [];
const head: string[] = [];
let current: { name: string; origin: string; lines: string[] } | null = null;
for (const line of watLines) {
  const start = /^  \(func \$([^ )]+)/.exec(line);
  if (start) {
    const name = start[1]!;
    current = { name, origin: name.startsWith("rt:") ? "runtime" : "yours", lines: [line] };
    functions.push(current);
  } else if (current && line.startsWith("  ")) {
    current.lines.push(line);
  } else if (current && line === ")") {
    current = null;
  } else if (current === null) {
    head.push(line);
  } else {
    current.lines.push(line);
  }
}

// Which source lines belong to which function. Today only a whole function maps to its source; the sieve has no
// functions of its own, so `main` is the program.
const mapping = [{ name: "main", from: 1, to: lines.length }];

const data = {
  program: { name: "Sieve of Eratosthenes (bench/sieve.oak)", source, lines },
  stdout: ran.stdout,
  module: { bytes: compiled.wasm.length, watLines: watLines.length, head, functions },
  mapping,
  // The numbers of `npm run bench` (README, "How fast"), Node, median of five runs.
  times: { compileMs: 1.1, compiledMs: 4.2, interpretedMs: 1270, interpretedTraceMs: 1253, ratio: 302 },
  machine: "Intel Core i3-9100F, Node 22.23.3",
  problems: [],
};
writeFileSync(join(root, "docs", "design", "compiler", "data.js"), `// Generated by scripts/mockup-compiler-data.ts. Real output of the compiler for the sieve; do not edit.\nwindow.CC = ${JSON.stringify(data, null, 1)};\n`);
console.log(`${functions.length} functions, ${compiled.wasm.length} bytes, ${watLines.length} lines of WAT; output ${JSON.stringify(ran.stdout.trim())}`);
console.log(functions.map((f) => `${f.name} (${f.origin}, ${f.lines.length} lines)`).join("\n"));
